import { readFileSync, writeFileSync, mkdirSync, renameSync, existsSync } from 'node:fs'

const DIR = 'scripts/regulations-seed'
const load = (c) => JSON.parse(readFileSync(`${DIR}/${c}.json`, 'utf8'))
const save = (c, s) => writeFileSync(`${DIR}/${c}.json`, JSON.stringify(s, null, 2) + '\n')
const p = (t) => `<p>${t}</p>`
const art = (title, lines) => [p(`<strong>${title}</strong>`), ...lines.map((l) => (l.startsWith('<table') ? l : p(l)))].join('')
const h2 = (t) => `<h2>${t}</h2>`
const td = (t) => `<td><p>${t}</p></td>`
const table = (header, rows) =>
  `<table><tbody><tr>${header.map((h) => td(`<strong>${h}</strong>`)).join('')}</tr>` +
  rows.map((r) => `<tr>${r.map(td).join('')}</tr>`).join('') + `</tbody></table>`
const DECIDED = '2026-11-27 대표 결정'

function replaceAll(html, pairs) {
  let out = html
  for (const [from, to] of pairs) {
    if (!out.includes(from)) throw new Error(`치환 대상 없음: ${from.slice(0, 50)}`)
    out = out.split(from).join(to)
  }
  return out
}

