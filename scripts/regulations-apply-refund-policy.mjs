const p = (t) => `<p>${t}</p>`
const art = (title, lines) => [p(`<strong>${title}</strong>`), ...lines.map(p)].join('')
const td = (t) => `<td><p>${t}</p></td>`
const table = (header, rows) =>
  `<table><tbody><tr>${header.map((h) => td(`<strong>${h}</strong>`)).join('')}</tr>` +
  rows.map((r) => `<tr>${r.map(td).join('')}</tr>`).join('') + `</tbody></table>`

/** html 에서 "제N조" 블록(해당 조 제목부터 다음 조/장/부칙 직전까지)을 새 html 로 바꾼다 */
function replaceArticle(html, number, newHtml) {
  const start = html.indexOf(`<p><strong>${number} `)
  if (start < 0) throw new Error(`${number} 없음`)
  const rest = html.slice(start + 1)
  const next = rest.search(/<p><strong>제\d+조(의\d+)? \(|<h2>/)
  const end = next < 0 ? html.length : start + 1 + next
  return html.slice(0, start) + newHtml + html.slice(end)
}

